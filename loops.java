//FOR LOOP
class forloop{
    public static void main(String[] args){
        for(int i=0;i<10;i++){
            System.out.print((i+1)+" ");
        }
    }
}
//WHILE LOOP
class whileloop{
    public static void main(String[] args){
        int i=0;
        while(i<10){
            System.out.print((i+1)+" ");
            i++;
        }
    }
}
//DO-WHILE
class dowhile{
    public static void main(String[] args){
        int i=0;
        do{
            System.out.print((i+1)+" ");
            i++;
        }while(i<10);
    }
}
